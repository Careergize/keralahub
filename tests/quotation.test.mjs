import assert from 'node:assert/strict';
import {readQuotationDetails,writeQuotationDetails,quotationAmount} from '../src/quotationDetails.js';
import {quotationDocument} from '../src/quotationDocument.js';
const details={rate:'9700',pricing:'person',travellers:'8',terms:'Our approved terms',notes:'Customer notes'};
assert.equal(quotationAmount(details),77600);
assert.equal(quotationAmount({...details,pricing:'group'}),9700);
assert.deepEqual(readQuotationDetails(writeQuotationDetails(details)),details);
assert.deepEqual(readQuotationDetails('Existing notes'),{notes:'Existing notes'});
for(const patch of [{rate:'-1'},{rate:'1.999'},{travellers:'0'},{travellers:'1.5'},{pricing:'invalid'}])assert.throws(()=>writeQuotationDetails({...details,...patch}));
const html=quotationDocument({record:{ID:'QUO-1',Description:'<script>alert(1)</script>',Amount:77600,Itinerary:'DAY 01\nArrival\n\nDAY 02\nDeparture'},details,customer:['C-1','Test Customer'],brand:{name:'KeralaHub'}});
assert.ok(html.includes('&lt;script&gt;'));
assert.ok(!html.includes('<script>alert'));
assert.ok(html.includes('77,600.00'));
assert.ok(html.includes('Our approved terms'));
assert.ok(!html.includes('Amount paid'));
const photos=quotationDocument({record:{Amount:100,Description:'Kerala'},details:{coverImage:'https://images.example.com/cover.jpg',days:[{title:'Munnar',description:'Tea gardens',image:'https://images.example.com/munnar.jpg'},{title:'Kochi',image:'javascript:alert(1)'}]}});
assert.ok(photos.includes('src="https://images.example.com/cover.jpg"'));
assert.ok(photos.includes('src="https://images.example.com/munnar.jpg"'));
assert.ok(photos.includes('DAY 02: Kochi'));
assert.ok(!photos.includes('src="javascript:'));
console.log('Passed: quotation pricing, persistence, legacy notes, invalid input and safe printable output.');
